import Foundation

private func line(_ obj: [String: Any]) -> Data { try! JSONSerialization.data(withJSONObject: obj) }
private func assistant(_ content: Any, at: String, sidechain: Bool = false) -> Data {
    line(["type": "assistant", "timestamp": at, "isSidechain": sidechain, "message": ["content": content]])
}
private func user(_ content: Any, meta: Bool = false) -> Data {
    line(["type": "user", "isMeta": meta, "message": ["content": content]])
}

func unreadTests() {
    test("replies since your last message") {
        let lines = [
            assistant([["type": "text", "text": "old reply"]], at: "2026-10-20T09:00:00.000Z"),
            user("please fix it"),
            assistant([["type": "text", "text": "On it."], ["type": "tool_use", "name": "Bash"]], at: "2026-10-20T10:00:00.000Z"),
            user([["type": "tool_result", "content": [["type": "text", "text": "ok"]]]]),
            assistant([["type": "tool_use", "name": "Bash"]], at: "2026-10-20T10:01:00.000Z"),    // no text: not a reply
            assistant([["type": "text", "text": "  "]], at: "2026-10-20T10:01:30.000Z"),          // blank
            assistant([["type": "text", "text": "subagent"]], at: "2026-10-20T10:02:00.000Z", sidechain: true),
            user("<task-notification>\n<task-id>x</task-id>"),
            user([["type": "text", "text": "<local-command-stdout>done</local-command-stdout>"]]),
            user("Caveat: generated by Claude Code", meta: true),
            assistant([["type": "text", "text": "Fixed."]], at: "2026-10-20T10:05:00.000Z"),
            assistant([["type": "text", "text": "no time"]], at: "not a date"),
            Data("not json \"type\":\"text\"".utf8),
            line(["type": "system", "message": ["content": [["type": "text", "text": "x"]]]]),
        ]
        let iso = ISO8601DateFormatter.withFractions
        expectEqual(SessionLoader.replies(in: lines), ["2026-10-20T10:00:00.000Z", "2026-10-20T10:05:00.000Z"].map { iso.date(from: $0)! })
        // No message from you in the tail: every reply counts.
        expectEqual(SessionLoader.replies(in: Array(lines.prefix(1))).count, 1)
        // A message you just typed: nothing unread.
        expect(SessionLoader.replies(in: lines + [user([["type": "text", "text": "thanks"], ["type": "image"]])]).isEmpty)
        // The newest reply, on one line, for a preview.
        expectEqual(SessionLoader.lastReply(in: lines), "Fixed.")
        let multi = assistant([["type": "text", "text": "## Done\n\n- **one** `a`\n  - [x] two\n> ~~old~~ __new__"], ["type": "text", "text": " "], ["type": "text", "text": "Next?"]],
                              at: "2026-10-20T11:00:00.000Z")
        expectEqual(SessionLoader.lastReply(in: lines + [multi]), "Done one a two old new Next?")
        expect(SessionLoader.lastReply(in: [user("hi")]) == nil)
    }
    test("loaded with the session, and cached with the title") {
        let box = Sandbox(); defer { box.cleanup() }
        box.write("claude/sessions/1.json", #"{"pid":1,"sessionId":"s","cwd":"/p/app","startedAt":1}"#)
        let url = box.write("claude/projects/-p-app/s.jsonl", [
            user("go"), assistant([["type": "text", "text": "Done."]], at: "2026-10-20T10:00:00.000Z"),
        ].map { String(decoding: $0, as: UTF8.self) }.joined(separator: "\n") + "\n")
        let (live, updates) = SessionLoader.loadLive(cache: [:], alive: { _ in true })
        expectEqual(live.first?.replies.count, 1)
        expectEqual(updates[url.path]?.replies.count, 1)
        let again = SessionLoader.loadLive(cache: updates, alive: { _ in true })
        expectEqual(again.0.first?.replies.count, 1) // from the cache
        expectEqual(live.first?.lastReply, "Done.")
        expectEqual(again.0.first?.lastReply, "Done.")
        expect(again.1.isEmpty)
    }
    test("unread counts and ⌘J goes to waiting, then unread sessions") {
        func s(_ id: String, _ status: SessionStatus, replies: [Double] = []) -> Session {
            Session(sessionId: id, pid: 1, cwd: "/p", name: nil, title: nil, status: status, waitingFor: nil, updatedAt: Date(),
                    transcriptURL: nil, replies: replies.map { Date(timeIntervalSince1970: $0) })
        }
        let a = s("a", .idle, replies: [100, 200, 300])
        expectEqual(SessionNav.unread(a, seen: Date(timeIntervalSince1970: 150)), 2)
        expectEqual(SessionNav.unread(a, seen: Date(timeIntervalSince1970: 300)), 0)
        let live = [s("w1", .waiting), a, s("b", .busy), s("w2", .waiting), s("c", .idle, replies: [1])]
        let unread: (Session) -> Int = { $0.replies.count }
        expectEqual(SessionNav.nextWaiting(live, after: nil, unread: unread), "w1")
        expectEqual(SessionNav.nextWaiting(live, after: "w1", unread: unread), "w2")
        expectEqual(SessionNav.nextWaiting(live, after: "w2", unread: unread), "a")
        expectEqual(SessionNav.nextWaiting(live, after: "a", unread: unread), "c")
        expectEqual(SessionNav.nextWaiting(live, after: "c", unread: unread), "w1")
        expectEqual(SessionNav.nextWaiting(live, after: "w2"), "w1") // without unread counts: waiting only
        expect(SessionNav.nextWaiting([s("b", .busy)], after: nil, unread: unread) == nil)
    }
    test("the first unread reply's text, to open there") {
        let lines = [
            user("go"),
            assistant([["type": "text", "text": "## Plan\n- **one** `x`"]], at: "2026-10-20T10:00:00.000Z"),
            assistant([["type": "text", "text": "> Done."]], at: "2026-10-20T10:05:00.000Z"),
        ]
        let texts = SessionLoader.replyTexts(in: lines)
        expectEqual(texts, ["Plan\none x", "Done."])
        let iso = ISO8601DateFormatter.withFractions
        var s = Session(sessionId: "s", pid: 1, cwd: "/", name: nil, title: nil, status: .idle, waitingFor: nil,
                        updatedAt: Date(), transcriptURL: nil, replies: SessionLoader.replies(in: lines), replyTexts: texts)
        expectEqual(SessionNav.firstUnread(s, seen: iso.date(from: "2026-10-20T10:01:00.000Z")!), "Done.")
        expectEqual(SessionNav.firstUnread(s, seen: .distantPast), "Plan\none x")
        expect(SessionNav.firstUnread(s, seen: .distantFuture) == nil)
        s.replyTexts = []
        expect(SessionNav.firstUnread(s, seen: .distantPast) == nil, "texts not loaded")
    }
}